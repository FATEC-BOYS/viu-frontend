import { test, expect, type Page, type BrowserContext } from '@playwright/test'
const api = 'http://127.0.0.1:3101'
const projetoBase = 'c000000000000000000000010'
const arquivo = { name: 'capa.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64') }
async function entrar(context: BrowserContext, tipo = 'designer') {
  await context.request.post(`${api}/auth/login`, { data: { email: `${tipo}@teste.local`, senha: 'teste' } })
}
async function subir(page: Page, projeto = projetoBase) {
  await page.goto(`/projetos/${projeto}?tab=artes`)
  await page.getByRole('button', { name: 'Subir nova arte', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByPlaceholder('Ex.: Banner - Lançamento').fill('Capa piloto')
  await dialog.getByRole('button', { name: 'Continuar', exact: true }).click()
  await dialog.locator('input[type=file]').setInputFiles(arquivo)
  await dialog.getByRole('button', { name: 'Continuar', exact: true }).click()
  await dialog.getByRole('switch', { name: 'Gerar link público', exact: true }).check()
  await dialog.getByRole('button', { name: 'Criar', exact: true }).click()
  await expect(dialog.getByText('Arte criada. O link público está pronto:')).toBeVisible()
  const link = await dialog.locator('input[readonly]').inputValue()
  await dialog.getByRole('button', { name: 'Concluir' }).click()
  return link
}
async function solicitar(page: Page) {
  await page.getByRole('button', { name: 'Solicitar aprovação de Capa piloto', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Solicitar', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}
test.beforeEach(async ({ request }) => { await request.post(`${api}/__reset`) })
test('cria projeto, sobe arte, gera link e cliente aprova', async ({ page, context, browser }) => {
  await entrar(context)
  await page.goto('/projetos')
  await page.getByRole('button', { name: 'Novo', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Nome do projeto', { exact: true }).fill('Campanha piloto')
  await dialog.getByPlaceholder('Buscar ou adicionar por e-mail…').fill('Cliente')
  await page.getByText('cliente@teste.local', { exact: true }).last().click()
  await dialog.getByRole('button', { name: 'Continuar', exact: true }).click()
  await expect(dialog.getByText('Todos precisam aprovar')).toHaveCount(0)
  await dialog.getByRole('checkbox').check()
  const salvo = page.waitForResponse(r => r.url() === `${api}/projetos` && r.request().method() === 'POST')
  await dialog.getByRole('button', { name: 'Criar projeto', exact: true }).click()
  const projeto = (await (await salvo).json()).data.id
  const link = await subir(page, projeto)
  await solicitar(page)
  const cliente = await browser.newContext({ viewport: { width: 390, height: 844 } })
  await entrar(cliente, 'cliente')
  const revisao = await cliente.newPage()
  await revisao.goto(link)
  await revisao.getByRole('button', { name: 'Aprovar', exact: true }).click()
  await expect(revisao.getByText('Aprovada', { exact: true }).first()).toBeVisible()
  await page.goto(`/projetos/${projeto}`)
  await expect(page.getByText('Tudo aprovado', { exact: true })).toBeVisible()
  await expect(page.getByText('100%', { exact: true })).toBeVisible()
  await expect(page.getByText(/Enviar para aprovação:/)).toHaveCount(0)
  await page.reload()
  await expect(page.getByText('Tudo aprovado', { exact: true })).toBeVisible()
  await expect(page.getByText('100%', { exact: true })).toBeVisible()
  await cliente.close()
})
test('pede ajustes, envia v2 e aprova somente a nova entrega', async ({ page, context, browser }) => {
  await entrar(context)
  const link = await subir(page)
  await solicitar(page)
  const cliente = await browser.newContext({ viewport: { width: 390, height: 844 } })
  await entrar(cliente, 'cliente')
  const revisao = await cliente.newPage()
  await revisao.goto(link)
  await revisao.getByRole('button', { name: 'Pedir ajustes', exact: true }).click()
  await revisao.getByPlaceholder('O que precisa mudar?').fill('Aumentar o título')
  await revisao.getByRole('button', { name: 'Enviar pedido', exact: true }).click()
  await page.goto(`/projetos/${projetoBase}?tab=artes`)
  await page.getByRole('button', { name: 'Nova versão de Capa piloto' }).click()
  await page.getByRole('dialog').locator('input[type=file]').setInputFiles(arquivo)
  await page.getByLabel('O que mudou nesta versão?').fill('Título aumentado conforme solicitado')
  await page.getByRole('button', { name: 'Criar nova versão', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await solicitar(page)
  await revisao.reload()
  await expect(revisao.getByText('v2', { exact: true }).first()).toBeVisible()
  await expect(revisao.getByText('O que mudou: Título aumentado conforme solicitado')).toBeVisible()
  await revisao.getByLabel('Versão exibida').selectOption('1')
  await expect(revisao.getByText(/Versão anterior · somente consulta/)).toBeVisible()
  await expect(revisao.getByRole('button', { name: 'Aprovar', exact: true })).toHaveCount(0)
  await revisao.getByLabel('Versão exibida').selectOption('2')
  await revisao.getByRole('button', { name: 'Aprovar', exact: true }).click()
  await page.goto(`/projetos/${projetoBase}?tab=approval`)
  await expect(page.getByText('Aprovada', { exact: true })).toBeVisible()
  await expect(page.getByText('Ajustes pedidos', { exact: true })).toHaveCount(0)
  await cliente.close()
})
test('não transforma falha de consulta em vazio e permite tentar novamente', async ({ page, context }) => {
  await entrar(context)
  await subir(page)
  await context.request.post(`${api}/__fail`, { data: { paths: ['/aprovacoes'] } })
  await page.goto(`/projetos/${projetoBase}?tab=approval`)
  await expect(page.getByRole('alert').filter({ hasText: 'Não foi possível carregar as aprovações.' })).toBeVisible()
  await expect(page.getByText('Nenhuma arte em aprovação.')).toHaveCount(0)
  await context.request.post(`${api}/__fail`, { data: { paths: [] } })
  await page.getByRole('button', { name: 'Tentar novamente', exact: true }).click()
  await expect(page.getByText(/Nenhuma arte em aprovação/)).toBeVisible()
})
